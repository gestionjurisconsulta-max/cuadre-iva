# -*- coding: utf-8 -*-
"""Historico de cuadres en PostgreSQL.

Guarda cada ejecucion completa --las lineas de los dos libros, las duplicadas con
su veredicto, los descuadres y los avisos-- para poder consultarlas despues por
rango de fechas y comparar trimestres entre si.

Dos fechas conviven y no significan lo mismo:

  fecha         la de expedicion de la factura
  periodo       el trimestre en cuyo libro se declaro

No coinciden siempre: una factura de marzo puede declararse en el libro del 2T.
Las consultas dejan elegir por cual filtrar.

La conexion se indica con un DSN, en la variable de entorno CUADRE_BD o pasando
`dsn` a cada funcion. Para levantar la base de desarrollo:

    docker compose up -d db
"""
import hashlib
import os
from datetime import datetime

import pandas as pd
from sqlalchemy import create_engine, text

VERSION_ESQUEMA = 2

# OJO con los tipos de los importes: en SQLite REAL son 8 bytes, pero en
# PostgreSQL son 4 y solo guardan unos 6 digitos significativos. Una cuota de
# 2.216.121,79 € se redondearia sola. Aqui van todos en DOUBLE PRECISION.
ESQUEMA = """
CREATE TABLE IF NOT EXISTS meta (
  clave TEXT PRIMARY KEY,
  valor TEXT
);

CREATE TABLE IF NOT EXISTS cargas (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  periodo       TEXT NOT NULL,
  ejecutado_en  TEXT NOT NULL,
  fichero_a3    TEXT,
  fichero_bilky TEXT,
  huella_a3     TEXT,
  huella_bilky  TEXT,
  lineas_a3     INTEGER,
  lineas_bilky  INTEGER,
  sociedades    INTEGER,
  cuota_a3      DOUBLE PRECISION,
  cuota_bilky   DOUBLE PRECISION,
  dif_cuota     DOUBLE PRECISION,
  cuadra        INTEGER,
  tasa_regla    DOUBLE PRECISION,
  duplicadas    INTEGER,
  duplicadas_accion INTEGER
);

CREATE TABLE IF NOT EXISTS lineas (
  carga_id   INTEGER NOT NULL REFERENCES cargas(id) ON DELETE CASCADE,
  periodo    TEXT NOT NULL,
  libro      TEXT NOT NULL,
  emp        TEXT,
  sociedad   TEXT,
  fecha      TEXT,
  nif_prov   TEXT,
  proveedor  TEXT,
  num        TEXT,
  num_clave  TEXT,
  tipofra    TEXT,
  tipo       DOUBLE PRECISION,
  base       DOUBLE PRECISION,
  cuota      DOUBLE PRECISION,
  total      DOUBLE PRECISION,
  iddoc      TEXT,
  enlace     TEXT
);

CREATE TABLE IF NOT EXISTS duplicadas (
  carga_id   INTEGER NOT NULL REFERENCES cargas(id) ON DELETE CASCADE,
  periodo    TEXT NOT NULL,
  emp        TEXT, sociedad TEXT,
  nif_prov   TEXT, proveedor TEXT,
  num_a3     TEXT, num_clave TEXT,
  fecha      TEXT, fechas TEXT,
  tipo DOUBLE PRECISION, base DOUBLE PRECISION,
  total DOUBLE PRECISION, cuota DOUBLE PRECISION,
  rep_a3 INTEGER, rep_bilky INTEGER, docs_bilky INTEGER,
  veredicto TEXT, sobrante DOUBLE PRECISION, enlace TEXT
);

CREATE TABLE IF NOT EXISTS descuadres (
  carga_id INTEGER NOT NULL REFERENCES cargas(id) ON DELETE CASCADE,
  periodo  TEXT NOT NULL,
  clase    TEXT NOT NULL,
  emp TEXT, sociedad TEXT,
  nif_prov TEXT, proveedor TEXT,
  num TEXT, fecha TEXT, tipo DOUBLE PRECISION,
  base_a DOUBLE PRECISION, cuota_a DOUBLE PRECISION,
  base_b DOUBLE PRECISION, cuota_b DOUBLE PRECISION,
  dif_cuota DOUBLE PRECISION
);

CREATE TABLE IF NOT EXISTS avisos (
  carga_id INTEGER NOT NULL REFERENCES cargas(id) ON DELETE CASCADE,
  periodo TEXT NOT NULL, nivel TEXT, texto TEXT
);

CREATE INDEX IF NOT EXISTS ix_lin_fecha    ON lineas(fecha);
CREATE INDEX IF NOT EXISTS ix_lin_periodo  ON lineas(periodo, libro);
CREATE INDEX IF NOT EXISTS ix_lin_emp      ON lineas(emp);
CREATE INDEX IF NOT EXISTS ix_lin_prov     ON lineas(nif_prov);
CREATE INDEX IF NOT EXISTS ix_lin_carga    ON lineas(carga_id);
CREATE INDEX IF NOT EXISTS ix_lin_dup      ON lineas(libro, emp, nif_prov, num_clave, tipo, base);
CREATE INDEX IF NOT EXISTS ix_dup_periodo  ON duplicadas(periodo);
CREATE INDEX IF NOT EXISTS ix_dup_emp      ON duplicadas(emp, veredicto);
CREATE INDEX IF NOT EXISTS ix_des_periodo  ON descuadres(periodo, clase);
CREATE INDEX IF NOT EXISTS ix_des_fecha    ON descuadres(fecha);
"""

DSN_DESARROLLO = "postgresql+psycopg://cuadre:cuadre@localhost:5433/cuadre"

_motores = {}          # dsn -> engine, con el esquema ya creado


def dsn_por_defecto():
    """DSN de la base. Se cambia con la variable de entorno CUADRE_BD."""
    return os.environ.get("CUADRE_BD") or DSN_DESARROLLO


def _normaliza(dsn):
    """Admite el DSN tal cual lo escribe todo el mundo y le pone el driver.

    'postgresql://...' y 'postgres://...' son lo que devuelven los proveedores
    de hosting; SQLAlchemy necesita saber ademas con que driver conectarse.
    """
    dsn = str(dsn or dsn_por_defecto())
    if dsn.startswith("postgres://"):
        dsn = "postgresql://" + dsn[len("postgres://"):]
    if dsn.startswith("postgresql://"):
        dsn = "postgresql+psycopg://" + dsn[len("postgresql://"):]
    return dsn


def motor(dsn=None):
    """Engine de SQLAlchemy, uno por DSN, con el esquema ya asegurado."""
    dsn = _normaliza(dsn)
    if dsn not in _motores:
        eng = create_engine(dsn, pool_pre_ping=True, pool_size=5, max_overflow=5,
                            future=True)
        with eng.begin() as cx:
            cx.execute(text(ESQUEMA))
            cx.execute(text("INSERT INTO meta(clave, valor) VALUES ('version', :v)"
                            " ON CONFLICT (clave) DO NOTHING"), {"v": str(VERSION_ESQUEMA)})
        _motores[dsn] = eng
    return _motores[dsn]


def cierra_motores():
    """Suelta las conexiones. Los tests lo usan entre bases distintas."""
    for eng in _motores.values():
        eng.dispose()
    _motores.clear()


def huella(origen):
    """sha256 de la entrada de un libro, sea una ruta, un buffer, una carpeta o
    una lista de cualquiera de ellos. Sirve para saber si un export ya se cargo.

    Usa la misma normalizacion que el lector, para no interpretar la entrada de
    dos formas distintas en dos sitios distintos.
    """
    from .lectura import entradas

    h = hashlib.sha256()
    for nombre, dato in entradas(origen):
        h.update(str(nombre).encode("utf-8"))
        if hasattr(dato, "read"):
            pos = dato.tell()
            dato.seek(0)
            for trozo in iter(lambda: dato.read(1 << 20), b""):
                h.update(trozo)
            dato.seek(pos)
        else:
            with open(dato, "rb") as f:
                for trozo in iter(lambda: f.read(1 << 20), b""):
                    h.update(trozo)
    return h.hexdigest()


def carga_previa(cx, periodo):
    return cx.execute(text("SELECT id, ejecutado_en FROM cargas WHERE periodo = :p"
                           " ORDER BY id"), {"p": periodo}).fetchall()


